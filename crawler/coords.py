# ===== 方向后缀偏移量 (度) =====
# 站名带方向后缀时, 相对城市中心点偏移
_DIRECTION_OFFSET = {
    "东": (0.0, 0.05),
    "西": (0.0, -0.05),
    "南": (-0.04, 0.0),
    "北": (0.04, 0.0),
    "东站": (0.0, 0.06),
    "西站": (0.0, -0.06),
    "南站": (-0.05, 0.0),
    "北站": (0.05, 0.0),
}


def get_city_center(city: str):
    """返回城市中心 (lat, lng), 查不到返回 None."""
    if city in CITY_COORDS:
        return CITY_COORDS[city]
    # 省名兜底
    for prov, coord in PROVINCE_COORDS.items():
        if prov in city:
            return coord
    return None


def station_coords(name: str, city: str) -> tuple | None:
    """根据站名+城市计算近似坐标.

    规则: 城市中心点 + 方向后缀偏移.
    返回 (lat, lng) 或 None (城市无坐标).
    """
    center = get_city_center(city)
    if center is None:
        # 尝试用站名本身匹配
        center = get_city_center(name)
    if center is None:
        return None

    lat, lng = center
    # 方向后缀
    for suffix, (d_lat, d_lng) in _DIRECTION_OFFSET.items():
        if name.endswith(suffix):
            return lat + d_lat, lng + d_lng
    return lat, lng
